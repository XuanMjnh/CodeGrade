export default function Icon({ name = 'code', className, ...props }) {
  const token = String(name)
    .split(/\s+/)
    .filter((x) => !['fa-solid', 'fa-regular', 'fa-brands'].includes(x))
    .find((x) => x.startsWith('fa-'));
  const Component = icons[token ? token.slice(3) : name] || HelpCircle;
  return (
    <Component
      data-icon={token ? token.slice(3) : name}
      aria-hidden="true"
      className={cn(
        'inline-block size-4 shrink-0 align-middle',
        String(name).includes('fa-spin') && 'animate-spin',
        className,
      )}
      {...props}
    />
  );
}
